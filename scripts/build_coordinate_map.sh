#!/usr/bin/env bash
# Builds mcp/data/coordinates/dmel_r5_to_r6.tsv from FlyBase's published release 5 to release 6 map
# (flybase/associated_files/Schroeder.Dmel_r5-to-r6_map.2014.6.12.txt.gz, interbase coordinates).
# Both start columns get +1 (1-based inclusive) and the rows are sorted; the result must equal the 1-based copy
# FlyBase ships in FlyBase/bulkfile-scripts (dmel_r5_to_r6/dmel_r5_to_r6_mapping.tsv, pinned sha256 below).
set -euo pipefail
cd "$(dirname "$0")/.."
URL=https://s3ftp.flybase.org/flybase/associated_files/Schroeder.Dmel_r5-to-r6_map.2014.6.12.txt.gz
FTP_SHA=b05a91abc671877c77e09ba0eb5ef4688801b1ef409e666335314224fa255221
GITHUB_SHA=2a0aae804b5ce1e20697b5e1eb91c04fbf0f74d4c612505a1cf21df78c8b5723   # bulkfile-scripts 10ed49d, unsorted 1-based copy
OUT=mcp/data/coordinates/dmel_r5_to_r6.tsv
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
curl -fsSL --max-time 120 -o "$TMP/map.txt.gz" "$URL"
echo "$FTP_SHA  $TMP/map.txt.gz" | sha256sum -c - >/dev/null
zcat "$TMP/map.txt.gz" | grep -v '^#' | awk -F'\t' 'BEGIN { OFS = "\t" } NF == 7 { print $1, $2 + 1, $3, $4, $5 + 1, $6, $7 }' > "$TMP/raw.tsv"
rows=$(wc -l < "$TMP/raw.tsv")
[ "$rows" -eq 6621 ] || { echo "expected 6621 rows, got $rows" >&2; exit 1; }
# Cross-check against FlyBase's own 1-based copy: same rows, independent of order.
[ "$(sort "$TMP/raw.tsv" | sha256sum | cut -d' ' -f1)" = "$(curl -fsSL --max-time 120 \
  https://raw.githubusercontent.com/FlyBase/bulkfile-scripts/10ed49d8919661bf8a5dd81a03ea7edff5e1d492/dmel_r5_to_r6/dmel_r5_to_r6_mapping.tsv \
  | tee "$TMP/github.tsv" | sort | sha256sum | cut -d' ' -f1)" ] || { echo "FTP map (+1) differs from bulkfile-scripts copy" >&2; exit 1; }
echo "$GITHUB_SHA  $TMP/github.tsv" | sha256sum -c - >/dev/null
# Validate: numeric coordinates, start <= end, equal lengths, +/- strand, no overlap within a source scaffold.
awk -F'\t' '$2 !~ /^[0-9]+$/ || $3 !~ /^[0-9]+$/ || $5 !~ /^[0-9]+$/ || $6 !~ /^[0-9]+$/ || $2 > $3 || $5 > $6 || ($3 - $2) != ($6 - $5) || ($7 != "+" && $7 != "-") { print "bad row " NR ": " $0; bad = 1 } END { exit bad }' "$TMP/raw.tsv"
sort -t$'\t' -k1,1 -k2,2n "$TMP/raw.tsv" | awk -F'\t' 'chr == $1 && $2 <= end { print "overlap at " $1 ":" $2; bad = 1 } { chr = $1; end = $3 } END { exit bad }'
mkdir -p "$(dirname "$OUT")"
{
  echo "# Dmel release 5 to release 6 coordinate map. Source: FlyBase, flybase/associated_files/Schroeder.Dmel_r5-to-r6_map.2014.6.12.txt.gz"
  echo "# (reciprocal best hit alignments, 2014-06-12), with 1 added to each start column. Licence: see LICENSE.bulkfile-scripts (BSD-3-Clause)."
  echo "# Coordinates are 1-based inclusive on both releases. strand - means the r5 block is reverse complemented in r6:"
  echo "# position p maps to to_end - (p - from_start). Generated by scripts/build_coordinate_map.sh; do not edit."
  printf 'from_chr\tfrom_start\tfrom_end\tto_chr\tto_start\tto_end\tstrand\n'
  sort -t$'\t' -k1,1 -k2,2n "$TMP/raw.tsv"
} > "$OUT"
echo "wrote $OUT: $(grep -vc '^#' "$OUT") lines including header"
